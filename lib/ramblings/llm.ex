  Module for interacting with LLM services to generate HTML from natural language prompts.
  """

  @doc """
  Generates HTML content from a natural language prompt describing a website.

  ## Examples

      iex> Ramblings.LLM.generate_html("a simple blog about cats")
      {:ok, "<html>...</html>"}

