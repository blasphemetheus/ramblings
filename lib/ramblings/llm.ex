  @doc """
  Async version of generate_html that can be used in LiveView processes.
  Returns immediately and sends a message when complete.
  """
  def generate_html_async(prompt, caller_pid) do
    Task.start(fn ->
      case generate_html(prompt) do
        {:ok, html} ->
          send(caller_pid, {:llm_result, :ok, html})

        {:error, reason} ->
          send(caller_pid, {:llm_result, :error, reason})
      end
    end)
  end
end
